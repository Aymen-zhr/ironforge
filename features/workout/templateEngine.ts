/**
 * Helper to get all preset routines flattened
 */
export function getAllPresetRoutines(): SplitRoutine[] {
  return PRESET_PROGRAMS.flatMap((p) => p.routines);
}

/**
 * Retrieve a specific preset routine by ID
 */
export function getPresetRoutineById(routineId: string): SplitRoutine | undefined {
  return getAllPresetRoutines().find((r) => r.id === routineId);
}

/**
 * Retrieve a preset program by ID
 */
export function getPresetProgramById(programId: string): PresetProgram | undefined {
  return PRESET_PROGRAMS.find((p) => p.id === programId);
}
